const STYLE_WORDS =
  /\s+(?:\d+pt|variable|var|thin|hairline|extralight|ultralight|light|book|regular|normal|text|medium|medm|semibold|demibold|bold|extrabold|ultrabold|heavy|black|italic|oblique|roman|vf)$/u;

/** “Poppins SemiBold”, “DM Sans 9pt” and “Inter Variable” come back from Chrome as platform names; strip them to the family. */
export const baseFamily = (family: string): string => {
  let name = family.toLowerCase().trim();
  for (let i = 0; i < 4; i += 1) {
    const shorter = name.replace(STYLE_WORDS, "");
    if (shorter === name) {
      break;
    }
    name = shorter;
  }
  return name;
};

const textFaces = (fonts: RenderedFont[]) => {
  const text = fonts.filter(
    (f) =>
      !MONO_FACES.test(f.family.toLowerCase()) &&
      !ICON_FACES.test(f.family.toLowerCase())
  );
  const total = text.reduce((sum, f) => sum + f.glyphs, 0);
  return { text, total };
};

const shareOf = (fonts: RenderedFont[], pattern: RegExp) => {
  const { text, total } = textFaces(fonts);
  if (total === 0) {
    return { share: 0, names: [] as string[] };
  }
  const matched = text.filter((f) => pattern.test(baseFamily(f.family)));
  return {
    share: matched.reduce((sum, f) => sum + f.glyphs, 0) / total,
    names: [...new Set(matched.map((f) => f.family))],
  };
};

const purpleKind = (
  stops: ColorStop[]
): "purple-pink" | "purple-blue" | "purple" | null => {
  const vivid = stops.filter((s) => s.alpha >= 0.15).map((s) => s.color);
  if (!vivid.some(isPurple)) {
    return null;
  }
  if (vivid.some(isPink)) {
    return "purple-pink";
  }
  if (vivid.some(isBlue)) {
    return "purple-blue";
  }
  return "purple";
};

/** Splits a computed box-shadow into layers, keeping commas inside colour functions. */
const shadowLayers = (css: string): { stops: ColorStop[]; blur: number }[] => {
  const layers: string[] = [];
  let depth = 0;
  let current = "";
  for (const ch of css) {
    if (ch === "(") {
      depth += 1;
    }
    if (ch === ")") {
      depth -= 1;
    }
    if (ch === "," && depth === 0) {
      layers.push(current);
      current = "";
    } else {
      current += ch;
    }
  }
  layers.push(current);
  return layers.map((layer) => {
    const lengths =
      layer.replaceAll(/[a-z]+\([^)]*\)/giu, "").match(/-?[\d.]+px/gu) ?? [];
    return {
      stops: colorStops(layer),
      // oxlint-disable-next-line unicorn/prefer-number-coercion -- reads the number off a "12px" length, which Number() turns into NaN
      blur: Number.parseFloat(lengths[2] ?? "0"),
    };
  });
};

const isGlow = (css: string): boolean =>
  shadowLayers(css).some(
    (layer) =>
      layer.blur >= 15 &&
      layer.stops.some((s) => s.alpha >= 0.15 && s.color.c >= 0.1)
  );

const wordCount = (text: string): number =>
  text.split(/\s+/u).filter(Boolean).length;

/**
 * A phrase counts once however long the page is, so years of blog posts or a long product page collect them by volume alone.
 * This scales a copy check down by how far the page runs past a landing page's length.
 */
const lengthDiscount = (text: string): number =>
  Math.min(1, LANDING_PAGE_WORDS / Math.max(wordCount(text), 1));

