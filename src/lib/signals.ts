export const SIGNAL_IDS = SIGNALS.map((s) => s.id);

const MIN_STRENGTH = 0.1;

/** One gradient can read as a purple wash, a decorative gradient and a halo at once. Together they cost no more than the heaviest. */
const GRADIENT_FAMILY = new Set(["purple", "gradient-washes", "orbs"]);
const GRADIENT_FAMILY_CAP = 16;

/** Trims the family's smaller finds so its sum stops at the cap, and says so in their evidence. A pattern found still costs 1. */
const capGradientFamily = (results: SignalResult[]): SignalResult[] => {
  let left = GRADIENT_FAMILY_CAP;
  const capped = new Map<string, number>();
  const family = results
    .filter((r) => r.hit && GRADIENT_FAMILY.has(r.id))
    .toSorted((a, b) => b.points - a.points);
  for (const result of family) {
    const points = Math.max(1, Math.min(result.points, left));
    left = Math.max(0, left - points);
    if (points < result.points) {
      capped.set(result.id, points);
    }
  }
  return results.map((result) => {
    const points = capped.get(result.id);
    if (points === undefined || !result.hit) {
      return result;
    }
    return {
      ...result,
      points,
      hit: {
        ...result.hit,
        evidence: `${result.hit.evidence}. Counted with the other gradient patterns, which cost ${GRADIENT_FAMILY_CAP} points at most together`,
      },
    };
  });
};

const isEnglish = (facts: Facts): boolean => {
  const lang = facts.rendered?.lang || facts.static.lang;
  return lang === "" || lang.startsWith("en");
};

export const evaluateSignals = (facts: Facts): SignalResult[] => {
  const english = isEnglish(facts);
  const results = SIGNALS.map((def) => {
    const checked =
      (!def.needsRender || facts.rendered !== null) &&
      (!def.englishOnly || english);
    const raw = checked ? def.detect(facts) : null;
    const hit = raw && raw.strength >= MIN_STRENGTH ? raw : null;
    return {
      id: def.id,
      category: def.category,
      title: def.title,
      weight: def.weight,
      why: def.why,
      fix: def.fix,
      hit,
      points: hit ? patternPoints(def.weight, hit.strength) : 0,
      checked,
    };
  });
  return capGradientFamily(results).toSorted((a, b) => b.points - a.points);
};

const GOOGLE_FAMILIES = new Set(GOOGLE_FONTS as string[]);
/** Webfonts share needed before a face counts as the page's own. */
const OWN_FACE_SHARE = 0.25;

/** True when the family, minus weight and size suffixes, is a Google Fonts family: free, and what generators pull from. */
export const isGoogleFont = (family: string): boolean =>
  GOOGLE_FAMILIES.has(family.toLowerCase().trim()) ||
  GOOGLE_FAMILIES.has(baseFamily(family));

const ownFaces = (fonts: RenderedFont[]): RenderedFont[] => {
  const { text, total } = textFaces(fonts);
  if (total === 0) {
    return [];
  }
  return text.filter(
    (f) =>
      f.webfont &&
      f.glyphs / total >= OWN_FACE_SHARE &&
      !isGoogleFont(f.family) &&
      !DEFAULT_FACES.test(baseFamily(f.family)) &&
      !SECOND_WAVE_SERIFS.test(baseFamily(f.family)) &&
      !SECOND_WAVE_SANS.test(baseFamily(f.family))
  );
};

/** Hand-made evidence. Generators pull type from Google Fonts; a licensed or drawn face means someone chose and paid for it. */
export const evaluateCredits = (facts: Facts): Credit[] => {
  const r = facts.rendered;
  if (!r) {
    return [];
  }
  const heading = ownFaces(r.headingFonts);
  const body = ownFaces(r.fonts);
  const face = heading[0] ?? body[0];
  if (!face) {
    return [];
  }
  const cssName = heading[0] ? r.faceNames.heading : r.faceNames.body;
  const named =
    cssName && cssName.toLowerCase() !== face.family.toLowerCase()
      ? `“${cssName}” (${face.family})`
      : `“${face.family}”`;
  return [
    {
      id: "own-typeface",
      title: "A typeface of its own",
      evidence: `${heading[0] ? "Headings" : "Body text"} use ${named}, a webfont that isn't on Google Fonts`,
      points: OWN_FACE_POINTS,
    },
  ];
};
